-- ล้างข้อมูลรายการแบบเก็บถาวร (หลังบ้าน · เฉพาะผู้ดูแลระบบ)
-- ย้ายข้อมูลรายการของโหมดปัจจุบัน (live หรือ trial-<รอบ>) ไปไว้ใน env "archive-<เลขชุด>" ที่ไม่มีหน้าจอไหนเห็น · ไม่ลบแถวใด
-- ข้อมูลหลัก (part, BOM, Model, ผัง, ช่องเก็บ, ผู้ใช้, สิทธิ์, ค่าตั้ง) ไม่ถูกแตะ
-- เลขเอกสารเดินต่อจากเดิม: ป้ายเก่าที่อาจยังติดกล่องอยู่จะสแกนแล้ว "ไม่พบ" แทนที่จะไปชนกับกล่องใหม่เลขเดียวกัน
-- กู้คืนชุดที่เก็บไว้ได้ เมื่ออยู่ในโหมดเดียวกับตอนล้างและโหมดนั้นยังไม่มีข้อมูลใหม่

create table if not exists public.env_archives (
  id             integer generated by default as identity primary key,
  from_env       text not null,
  archive_env    text not null unique,
  counts         jsonb not null default '{}',
  note           text,
  archived_by    uuid references auth.users (id),
  archived_code  text,
  archived_at    timestamptz not null default now(),
  restored_by    uuid references auth.users (id),
  restored_code  text,
  restored_at    timestamptz
);
comment on table public.env_archives is 'ประวัติการล้างข้อมูลรายการแบบเก็บถาวร · แถวของชุดยังอยู่ในตารางเดิมโดย env = archive_env';

alter table public.env_archives enable row level security;
do $$
begin
  if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = 'env_archives' and policyname = 'env_archives read by admin') then
    create policy "env_archives read by admin" on public.env_archives for select to authenticated using (public.staff_role() = 'admin');
  end if;
end;
$$;

-- จำนวนแถวของตารางรายการใน env หนึ่ง (ตารางลูก เช่น grn_lines, lpn_items, requisition_lines ตามแม่ผ่าน FK)
create or replace function public.env_counts(p_env text)
returns jsonb
language sql stable security definer set search_path = public
as $$
  select jsonb_build_object(
    'grns',           (select count(*) from public.grns where env = p_env),
    'lpns',           (select count(*) from public.lpns where env = p_env),
    'wms_tx',         (select count(*) from public.wms_tx where env = p_env),
    'requisitions',   (select count(*) from public.requisitions where env = p_env),
    'invoices',       (select count(*) from public.invoices where env = p_env),
    'packing_lists',  (select count(*) from public.packing_lists where env = p_env),
    'stock_counts',   (select count(*) from public.stock_counts where env = p_env),
    'stock_closings', (select count(*) from public.stock_closings where env = p_env),
    'print_jobs',     (select count(*) from public.print_jobs where env = p_env))
$$;

-- กันรายการใหม่แทรกระหว่างล้าง/กู้คืน (อ่านได้ตามปกติ งานเขียนรอจนเสร็จ)
create or replace function public.env_lock()
returns void
language plpgsql security definer set search_path = public
as $$
begin
  lock table public.stock_closings, public.requisitions, public.wms_tx, public.lpns, public.grns, public.packing_lists,
    public.invoices, public.stock_counts, public.print_jobs in share row exclusive mode;
end;
$$;

-- ย้ายข้อมูลรายการทั้งหมดของ env หนึ่งไปอีก env (เรียกหลัง env_lock)
-- ทริกเกอร์ล็อกเดือนของใบเบิกดูการปิดยอดของ env ปัจจุบัน: ย้ายออกจาก env ปัจจุบัน ⇒ ปิดยอดไปก่อน · ย้ายเข้า ⇒ ปิดยอดตามทีหลัง
create or replace function public.env_move(p_from text, p_to text)
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  v jsonb := '{}';
  n bigint;
  t text;
begin
  foreach t in array case when p_to = public.wms_env()
      then array['requisitions', 'wms_tx', 'lpns', 'grns', 'packing_lists', 'invoices', 'stock_counts', 'print_jobs', 'stock_closings']
      else array['stock_closings', 'requisitions', 'wms_tx', 'lpns', 'grns', 'packing_lists', 'invoices', 'stock_counts', 'print_jobs'] end
  loop
    execute format('update public.%I set env = $1 where env = $2', t) using p_to, p_from;
    get diagnostics n = row_count;
    v := v || jsonb_build_object(t, n);
  end loop;
  return v;
end;
$$;

-- ล้างข้อมูลรายการของโหมดปัจจุบันเก็บเป็นชุดใหม่ (ภายใน: ผ่าน admin_archive_env หรือผู้ดูแลฐานข้อมูล)
create or replace function public.env_archive_now(p_note text default null, p_by uuid default null, p_code text default null)
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  v_from text := public.wms_env();
  v_id integer;
  v_to text;
  v_counts jsonb;
begin
  perform public.env_lock();
  if not exists (select 1 from jsonb_each_text(public.env_counts(v_from)) where value::bigint > 0) then
    raise exception 'ไม่มีข้อมูลรายการในโหมดนี้ให้ล้าง';
  end if;
  v_id := nextval(pg_get_serial_sequence('public.env_archives', 'id'));
  v_to := 'archive-' || v_id;
  v_counts := public.env_move(v_from, v_to);
  insert into public.env_archives (id, from_env, archive_env, counts, note, archived_by, archived_code)
  values (v_id, v_from, v_to, v_counts, nullif(btrim(p_note), ''), p_by, p_code);
  return jsonb_build_object('id', v_id, 'fromEnv', v_from, 'counts', v_counts);
end;
$$;

-- ปุ่มในหลังบ้าน: พิมพ์ "ล้างข้อมูล" ยืนยัน
create or replace function public.admin_archive_env(p_confirm text, p_note text default null)
returns jsonb
language plpgsql security definer set search_path = public
as $$
begin
  perform public.admin_only();
  if btrim(coalesce(p_confirm, '')) <> 'ล้างข้อมูล' then
    raise exception 'พิมพ์คำว่า "ล้างข้อมูล" ให้ตรงเพื่อยืนยัน';
  end if;
  return public.env_archive_now(p_note, auth.uid(), public.my_code());
end;
$$;

-- กู้คืนชุดที่เก็บไว้กลับเข้าโหมดเดิม: ต้องอยู่ในโหมดนั้นและโหมดนั้นยังว่าง (กันข้อมูลสองชุดปนกัน)
create or replace function public.admin_restore_archive(p_id integer)
returns jsonb
language plpgsql security definer set search_path = public
as $$
declare
  v_env text := public.wms_env();
  a public.env_archives;
  v_counts jsonb;
begin
  perform public.admin_only();
  perform public.env_lock();
  select * into a from public.env_archives where id = p_id for update;
  if not found then raise exception 'ไม่พบชุดข้อมูลที่เก็บไว้'; end if;
  if a.restored_at is not null then raise exception 'ชุดนี้กู้คืนไปแล้ว'; end if;
  if a.from_env <> v_env then
    raise exception 'ชุดนี้ล้างมาจาก% · สลับไปโหมดนั้นก่อนจึงจะกู้คืนได้',
      case when a.from_env = 'live' then 'โหมดใช้งานจริง' else 'โหมดทดลอง รอบ ' || replace(a.from_env, 'trial-', '') end;
  end if;
  if exists (select 1 from jsonb_each_text(public.env_counts(v_env)) where value::bigint > 0) then
    raise exception 'โหมดนี้มีข้อมูลใหม่แล้ว · ล้างข้อมูลปัจจุบันเก็บไว้ก่อน แล้วจึงกู้คืนชุดนี้';
  end if;
  v_counts := public.env_move(a.archive_env, v_env);
  update public.env_archives set restored_at = now(), restored_by = auth.uid(), restored_code = public.my_code() where id = p_id;
  return jsonb_build_object('id', p_id, 'counts', v_counts);
end;
$$;

-- หน้าหลังบ้าน: จำนวนข้อมูลของโหมดปัจจุบัน + รายการชุดที่เก็บไว้
create or replace function public.admin_env_summary()
returns jsonb
language plpgsql stable security definer set search_path = public
as $$
declare
  v_env text;
  v_counts jsonb;
  v_empty boolean;
begin
  perform public.admin_only();
  v_env := public.wms_env();
  v_counts := public.env_counts(v_env);
  v_empty := not exists (select 1 from jsonb_each_text(v_counts) where value::bigint > 0);
  return jsonb_build_object('env', v_env, 'counts', v_counts, 'archives', coalesce((
    select jsonb_agg(jsonb_build_object(
      'id', a.id, 'fromEnv', a.from_env, 'counts', a.counts, 'note', a.note,
      'archivedCode', a.archived_code, 'archivedAt', a.archived_at,
      'restoredCode', a.restored_code, 'restoredAt', a.restored_at,
      'restorable', a.restored_at is null and a.from_env = v_env and v_empty) order by a.id desc)
    from public.env_archives a), '[]'));
end;
$$;

-- สิทธิ์เรียกฟังก์ชัน
do $$
declare
  f text;
begin
  foreach f in array array['admin_archive_env(text, text)', 'admin_restore_archive(integer)', 'admin_env_summary()'] loop
    execute format('revoke all on function public.%s from public, anon', f);
    execute format('grant execute on function public.%s to authenticated', f);
  end loop;
  foreach f in array array['env_counts(text)', 'env_lock()', 'env_move(text, text)', 'env_archive_now(text, uuid, text)'] loop
    execute format('revoke all on function public.%s from public, anon, authenticated', f);
  end loop;
end;
$$;
